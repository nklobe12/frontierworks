def compass_frame(i, n, main='#c0392b'):
    img = item('compass', '#6b7280')
    px = img.load()
    ang = 2 * math.pi * i / n
    cx, cy = 7.5, 8.5
    for t in range(0, 5):
        x = int(round(cx + math.sin(ang) * t))
        y = int(round(cy - math.cos(ang) * t))
        if 0 <= x < 16 and 0 <= y < 16:
            px[x, y] = rgb(main) + (255,)
    for t in range(1, 4):
        x = int(round(cx - math.sin(ang) * t))
        y = int(round(cy + math.cos(ang) * t))
        if 0 <= x < 16 and 0 <= y < 16:
            px[x, y] = (220, 220, 230, 255)
    px[7, 8] = (30, 30, 30, 255)
    return img


def sheet(images, scale=6, cols=12):
    """Contact sheet for visual checking."""
    rows = (len(images) + cols - 1) // cols
    out = Image.new('RGBA', (cols * 16 * scale + cols * 4, rows * 16 * scale + rows * 4), (60, 60, 70, 255))
    for i, im in enumerate(images):
        im2 = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        x = (i % cols) * (16 * scale + 4)
        y = (i // cols) * (16 * scale + 4)
        out.alpha_composite(im2.crop((0, 0, 16 * scale, 16 * scale)), (x, y))
    return out
