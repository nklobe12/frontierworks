def blank(c=(0, 0, 0, 0)):
    return Image.new('RGBA', (16, 16), c)


def noise_fill(base, seed, var=0.12, size=16, speck=0.0, speck_color=None):
    img = Image.new('RGBA', (size, size))
    px = img.load()
    c = rgb(base) if isinstance(base, str) else base
    for y in range(size):
        for x in range(size):
            n = rnd(seed, x, y)
            n2 = rnd(seed + 'b', x // 2, y // 2)
            v = 1.0 + (n - 0.5) * var * 1.2 + (n2 - 0.5) * var
            col = (clamp(c[0] * v), clamp(c[1] * v), clamp(c[2] * v), 255)
            if speck and rnd(seed + 's', x, y) < speck:
                sc = rgb(speck_color) if isinstance(speck_color, str) else speck_color
                col = (sc[0], sc[1], sc[2], 255)
            px[x, y] = col
    return img


def stone(base, seed, style='rough'):
    """Natural stone. styles: rough, smooth, layered, mottled."""
    c = rgb(base)
    img = noise_fill(base, seed, 0.16 if style == 'rough' else 0.09)
    px = img.load()
    if style == 'layered':
        for y in range(16):
            band = (hsh(seed, 'band', y // 3) % 100) / 100.0
            for x in range(16):
                r, g, b, a = px[x, y]
                f = 0.9 + band * 0.2
                px[x, y] = (clamp(r * f), clamp(g * f), clamp(b * f), 255)
    elif style == 'mottled':
        for i in range(10):
            cx, cy = hsh(seed, 'm', i) % 16, hsh(seed, 'n', i) % 16
            f = 0.82 if i % 2 else 1.16
            for dx in range(-1, 2):
                for dy in range(-1, 2):
                    if abs(dx) + abs(dy) <= 1:
                        x, y = (cx + dx) % 16, (cy + dy) % 16
                        r, g, b, a = px[x, y]
                        px[x, y] = (clamp(r * f), clamp(g * f), clamp(b * f), 255)
    elif style == 'veined':
        dark = shade(c, 0.72)
        x = hsh(seed, 'v') % 16
        for y in range(16):
            px[x % 16, y] = dark
            if rnd(seed, 'vv', y) < 0.5:
                x += 1 if rnd(seed, 'dir', y) < 0.6 else -1
        x2 = hsh(seed, 'v2') % 16
        for y in range(8, 16):
            px[x2 % 16, y] = shade(c, 0.82)
            x2 += 1
    return img


