def fix_template(rows):
    """Templates are hand-typed; normalise any stray spaces to the neighbouring shade."""
    out = []
    for row in rows:
        r = list(row.ljust(16, '.')[:16])
        for i, ch in enumerate(r):
            if ch == ' ':
                r[i] = r[i - 1] if i > 0 and r[i - 1] not in '.K' else '2'
        out.append(''.join(r))
    return out


for _k in list(T.keys()):
    T[_k] = fix_template(T[_k])


def item(kind, main, handle=None, accent=None):
    """Render an item template with a material colour."""
    return from_template(T[kind], palette(main, handle, accent))


