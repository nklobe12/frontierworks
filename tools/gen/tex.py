def armor_layer(color, layer, seed):
    """64x32 armor layer in the vanilla humanoid UV layout."""
    c = rgb(color)
    img = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
    px = img.load()

    def box(u, v, w, h, d, f=1.0):
        # unwrapped cuboid: top/bottom at (u+d, v) size w x d, sides at row v+d
        regions = [
            (u + d, v, w, d, 1.15), (u + d + w, v, w, d, 0.8),
            (u, v + d, d, h, 0.85), (u + d, v + d, w, h, 1.0),
            (u + d + w, v + d, d, h, 0.85), (u + d + w + d, v + d, w, h, 0.9),
        ]
        for (x0, y0, ww, hh, sh) in regions:
            for y in range(y0, y0 + hh):
                for x in range(x0, x0 + ww):
                    if 0 <= x < 64 and 0 <= y < 32:
                        n = 0.92 + rnd(seed, x, y) * 0.16
                        edge = (x == x0 or y == y0 or x == x0 + ww - 1 or y == y0 + hh - 1)
                        k = sh * f * n * (0.72 if edge else 1.0)
                        px[x, y] = (clamp(c[0] * k), clamp(c[1] * k), clamp(c[2] * k), 255)

    if layer == 1:
        box(0, 0, 8, 8, 8)       # head
        # visor slit
        for x in range(9, 15):
            px[x, 11] = (20, 20, 24, 255)
        box(16, 16, 8, 12, 4)    # body
        box(40, 16, 4, 12, 4)    # arm
        box(0, 16, 4, 12, 4)     # leg/boot
    else:
        box(16, 16, 8, 12, 4, 0.95)  # belt area
        box(0, 16, 4, 12, 4, 0.95)   # legs
    return img


def humanoid_skin(main, secondary, skin, seed, eyes=(255, 60, 40), style='mob'):
    """64x64 humanoid texture in the vanilla zombie/player layout."""
    img = Image.new('RGBA', (64, 64), (0, 0, 0, 0))
    px = img.load()
    m, s, k = rgb(main), rgb(secondary), rgb(skin)

    def fill(x0, y0, w, h, col, var=0.1, sd='a'):
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                n = 1.0 + (rnd(seed + sd, x, y) - 0.5) * var * 2
                px[x, y] = (clamp(col[0] * n), clamp(col[1] * n), clamp(col[2] * n), 255)

    def cuboid(u, v, w, h, d, col, var=0.12, sd='a'):
        fill(u + d, v, w, d, col, var, sd)
        fill(u + d + w, v, w, d, col, var, sd)
        fill(u, v + d, d + w + d + w, h, col, var, sd)

    cuboid(0, 0, 8, 8, 8, k, 0.1, 'h')        # head
    cuboid(16, 16, 8, 12, 4, m, 0.12, 'b')    # body
    cuboid(40, 16, 4, 12, 4, m, 0.12, 'r')    # right arm
    cuboid(32, 48, 4, 12, 4, m, 0.12, 'l')    # left arm
    cuboid(0, 16, 4, 12, 4, s, 0.12, 'g')     # right leg
    cuboid(16, 48, 4, 12, 4, s, 0.12, 'k')    # left leg
    # hands use skin colour
    for (u, v) in ((40, 16), (32, 48)):
        fill(u, v + 4 + 9, 16, 3, k, 0.08, 'hand')
    # face: eyes and mouth on the front face (8..16, 8..16)
    e = eyes
    for (x, y) in ((9, 12), (10, 12), (13, 12), (14, 12)):
        px[x, y] = e + (255,)
    for x in range(10, 14):
        px[x, 14] = shade(k, 0.5)
    # hat/hair band
    for x in range(8, 16):
        px[x, 8] = shade(s, 0.9)
        px[x, 9] = shade(s, 1.0)
    # belt
    for x in range(20, 28):
        px[x, 30] = shade(s, 0.6)
        px[x, 31] = shade(s, 0.7)
    return img


def box_texture(w, h, boxes, seed):
    """Texture for a generated box model: boxes = [(u,v,sx,sy,sz,color)]."""
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    px = img.load()
    for (u, v, sx, sy, sz, color) in boxes:
        c = rgb(color)
        faces = [
            (u + sz, v, sx, sz, 1.15), (u + sz + sx, v, sx, sz, 0.75),
            (u, v + sz, sz, sy, 0.85), (u + sz, v + sz, sx, sy, 1.0),
            (u + sz + sx, v + sz, sz, sy, 0.85), (u + sz + sx + sz, v + sz, sx, sy, 0.92),
        ]
        for (x0, y0, ww, hh, sh) in faces:
            for y in range(y0, y0 + hh):
                for x in range(x0, x0 + ww):
                    if 0 <= x < w and 0 <= y < h:
                        n = 0.9 + rnd(seed + color, x, y) * 0.2
                        edge = x == x0 or y == y0 or x == x0 + ww - 1 or y == y0 + hh - 1
                        k = sh * n * (0.75 if edge and ww > 2 and hh > 2 else 1.0)
                        px[x, y] = (clamp(c[0] * k), clamp(c[1] * k), clamp(c[2] * k), 255)
    return img


