"""Procedural 16x16 pixel-art texture generator for Lodestar.

Everything here is original art built from shape templates + colour ramps, so the pack ships
no copied Minecraft textures. Templates use:
  '.' transparent   'K' outline (darkest)   '1'..'5' main ramp dark->light   'W' highlight
  'a' 'b' 'c' handle/secondary ramp dark->light   'p' 'q' 'r' accent ramp dark->light
  'g' 'h' 'i' neutral greys dark->light           'k' near-black          'w' white
"""
import colorsys
import hashlib
import math
from PIL import Image

# ----------------------------------------------------------------------------- colour utils

def rgb(hexstr):
    if isinstance(hexstr, tuple):
        return hexstr[:3]
    hexstr = hexstr.lstrip('#')
    if len(hexstr) == 3:
        hexstr = ''.join(ch * 2 for ch in hexstr)
    return tuple(int(hexstr[i:i + 2], 16) for i in (0, 2, 4))


def clamp(v):
    return max(0, min(255, int(round(v))))


def shade(c, l_mul=1.0, l_add=0.0, s_mul=1.0, h_shift=0.0):
    r, g, b = [x / 255.0 for x in c[:3]]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l = max(0.0, min(1.0, l * l_mul + l_add))
    s = max(0.0, min(1.0, s * s_mul))
    h = (h + h_shift) % 1.0
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return (clamp(r * 255), clamp(g * 255), clamp(b * 255), 255)


def ramp(base):
    """6-step ramp [outline, dark, mid-dark, base, light, highlight] + 'W'."""
    c = rgb(base) if isinstance(base, str) else base
    return {
        'K': shade(c, 0.32, 0.0, 1.1, 0.02),
        '1': shade(c, 0.58, 0.0, 1.05, 0.012),
        '2': shade(c, 0.80, 0.0, 1.0, 0.005),
        '3': shade(c, 1.0, 0.0, 1.0),
        '4': shade(c, 1.0, 0.12, 0.95, -0.005),
        '5': shade(c, 1.0, 0.24, 0.9, -0.01),
        'W': shade(c, 1.0, 0.40, 0.7, -0.015),
    }


def sub_ramp(base, chars=('a', 'b', 'c')):
    c = rgb(base) if isinstance(base, str) else base
    return {chars[0]: shade(c, 0.6), chars[1]: shade(c, 1.0), chars[2]: shade(c, 1.0, 0.15)}


GREYS = {'g': (70, 70, 76, 255), 'h': (128, 128, 136, 255), 'i': (190, 190, 198, 255),
         'k': (24, 24, 28, 255), 'w': (250, 250, 250, 255)}
WOOD = sub_ramp('#8a5a2b')


def palette(main, handle=None, accent=None):
    p = dict(GREYS)
    p.update(ramp(main))
    p.update(sub_ramp(handle) if handle else WOOD)
    if accent:
        p.update(sub_ramp(accent, ('p', 'q', 'r')))
    else:
        p.update(sub_ramp('#e0e0ff', ('p', 'q', 'r')))
    return p


def hsh(*parts):
    return int(hashlib.md5('|'.join(str(p) for p in parts).encode()).hexdigest()[:8], 16)


def rnd(seed, *xy):
    return (hsh(seed, *xy) % 10000) / 10000.0


def from_template(rows, pal, size=16):
    assert len(rows) == size, 'template needs %d rows, got %d' % (size, len(rows))
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == size, 'row %d has %d chars: %r' % (y, len(row), row)
        for x, ch in enumerate(row):
            if ch == '.' or ch == ' ':
                continue
            px[x, y] = pal[ch]
    return img


def tint_image(img, color, strength=1.0):
    c = rgb(color)
    out = img.copy()
    px = out.load()
    for y in range(out.height):
        for x in range(out.width):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            lum = (0.3 * r + 0.59 * g + 0.11 * b) / 255.0
            nr = c[0] * lum * 1.25
            ng = c[1] * lum * 1.25
            nb = c[2] * lum * 1.25
            px[x, y] = (clamp(r + (nr - r) * strength), clamp(g + (ng - g) * strength), clamp(b + (nb - b) * strength), a)
    return out


def overlay(base, top):
    out = base.copy()
    out.alpha_composite(top)
    return out


