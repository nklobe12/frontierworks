def ore_overlay(base, seed, style='blobs', density=1.0):
    """Transparent overlay of mineral clusters, composited over stone/deepslate in the model."""
    r = ramp(base)
    img = blank()
    px = img.load()
    count = int((5 if style == 'blobs' else 9) * density)
    pts = []
    tries = 0
    while len(pts) < count and tries < 300:
        tries += 1
        x, y = 1 + hsh(seed, 'x', tries) % 13, 1 + hsh(seed, 'y', tries) % 13
        if all(abs(x - a) + abs(y - b) > 4 for a, b in pts):
            pts.append((x, y))
    for i, (x, y) in enumerate(pts):
        if style == 'blobs':
            shape = [(0, 0), (1, 0), (0, 1), (1, 1)]
            if hsh(seed, 'e', i) % 2:
                shape += [(2, 0), (2, 1)]
            if hsh(seed, 'f', i) % 3 == 0:
                shape += [(0, 2), (1, 2)]
        elif style == 'gem':
            shape = [(1, 0), (0, 1), (1, 1), (2, 1), (1, 2)]
        else:  # specks
            shape = [(0, 0), (1, 0)] if i % 2 else [(0, 0), (0, 1)]
        for dx, dy in shape:
            xx, yy = x + dx, y + dy
            if 0 <= xx < 16 and 0 <= yy < 16:
                px[xx, yy] = r['3']
        # shading: top-left highlight, bottom-right dark, outline
        for dx, dy in shape:
            xx, yy = x + dx, y + dy
            if 0 <= xx < 16 and 0 <= yy < 16:
                if (dx - 1, dy) not in shape and (dx, dy - 1) not in shape:
                    px[xx, yy] = r['W']
                elif (dx + 1, dy) not in shape and (dx, dy + 1) not in shape:
                    px[xx, yy] = r['1']
                elif (dx, dy - 1) not in shape:
                    px[xx, yy] = r['4']
        for dx, dy in shape:
            for ox, oy in ((1, 0), (0, 1)):
                xx, yy = x + dx + ox, y + dy + oy
                if (dx + ox, dy + oy) not in shape and 0 <= xx < 16 and 0 <= yy < 16 and px[xx, yy][3] == 0:
                    px[xx, yy] = r['K'][:3] + (200,)
    return img


