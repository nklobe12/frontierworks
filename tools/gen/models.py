"""Box entity models: one spec -> Java EntityModel class + matching texture (auto UV packing)."""
from PIL import Image

from . import tex


class Part:
    def __init__(self, name, pivot, cubes, parent=None, anim=None, rot=(0, 0, 0)):
        self.name = name
        self.pivot = pivot
        self.cubes = cubes  # list of (x, y, z, w, h, d, colour[, dilation])
        self.parent = parent
        self.anim = anim
        self.rot = rot
        self.uv = []


class BoxModel:
    def __init__(self, cls, layer, tex_w=64, tex_h=64):
        self.cls = cls
        self.layer = layer
        self.tw = tex_w
        self.th = tex_h
        self.parts = []
        self._packed = False

    def part(self, name, pivot, cubes, parent=None, anim=None, rot=(0, 0, 0)):
        p = Part(name, pivot, cubes, parent, anim, rot)
        self.parts.append(p)
        return p

    def pack(self):
        """Shelf-pack every cube's UV net into the texture."""
        if self._packed:
            return
        self._packed = True
        boxes = []
        for p in self.parts:
            p.uv = [None] * len(p.cubes)
            for i, c in enumerate(p.cubes):
                w, h, d = c[3], c[4], c[5]
                boxes.append((2 * (d + w), d + h, p, i))
        boxes.sort(key=lambda b: -b[1])
        x = y = shelf = 0
        for (bw, bh, p, i) in boxes:
            if x + bw > self.tw:
                x = 0
                y += shelf
                shelf = 0
            if y + bh > self.th:
                # grow texture height
                self.th *= 2
            p.uv[i] = (x, y)
            x += bw
            shelf = max(shelf, bh)

    def texture(self, seed):
        self.pack()
        img = Image.new('RGBA', (self.tw, self.th), (0, 0, 0, 0))
        px = img.load()
        for p in self.parts:
            for (u, v), c in zip(p.uv, p.cubes):
                w, h, d, color = int(c[3]), int(c[4]), int(c[5]), c[6]
                col = tex.rgb(color)
                faces = [(u + d, v, w, d, 1.15), (u + d + w, v, w, d, 0.72), (u, v + d, d, h, 0.85), (u + d, v + d, w, h, 1.0),
                         (u + d + w, v + d, d, h, 0.85), (u + d + w + d, v + d, w, h, 0.92)]
                for (x0, y0, ww, hh, sh) in faces:
                    for yy in range(y0, y0 + hh):
                        for xx in range(x0, x0 + ww):
                            if 0 <= xx < self.tw and 0 <= yy < self.th:
                                n = 0.9 + tex.rnd(seed + str(color), xx, yy) * 0.2
                                edge = (xx == x0 or yy == y0 or xx == x0 + ww - 1 or yy == y0 + hh - 1) and ww > 2 and hh > 2
                                k = sh * n * (0.78 if edge else 1.0)
                                px[xx, yy] = (tex.clamp(col[0] * k), tex.clamp(col[1] * k), tex.clamp(col[2] * k), 255)
                # optional face details: 'eyes' marker colour on the front face
                if len(c) > 7 and c[7] == 'eyes':
                    fx, fy = u + d, v + d
                    ey = fy + max(1, h // 3)
                    for ex in (fx + max(1, w // 4), fx + w - 1 - max(1, w // 4)):
                        if 0 <= ex < self.tw and 0 <= ey < self.th:
                            px[ex, ey] = (255, 60, 40, 255)
                elif len(c) > 7 and c[7] == 'glow':
                    fx, fy = u + d, v + d
                    for yy in range(fy + 1, fy + h - 1):
                        for xx in range(fx + 1, fx + w - 1):
                            if 0 <= xx < self.tw and 0 <= yy < self.th:
                                px[xx, yy] = (120, 230, 255, 255)
        return img

    def java(self, pkg, modid):
        self.pack()
        fields = [p for p in self.parts]
        L = []
        L.append('// GENERATED by tools/gen/models.py - do not edit')
        L.append('package %s;' % pkg)
        L.append('')
        for imp in ('com.mojang.blaze3d.vertex.PoseStack', 'com.mojang.blaze3d.vertex.VertexConsumer', 'net.minecraft.client.model.EntityModel',
                    'net.minecraft.client.model.geom.ModelLayerLocation', 'net.minecraft.client.model.geom.ModelPart',
                    'net.minecraft.client.model.geom.PartPose', 'net.minecraft.client.model.geom.builders.CubeDeformation',
                    'net.minecraft.client.model.geom.builders.CubeListBuilder', 'net.minecraft.client.model.geom.builders.LayerDefinition',
                    'net.minecraft.client.model.geom.builders.MeshDefinition', 'net.minecraft.client.model.geom.builders.PartDefinition',
                    'net.minecraft.resources.ResourceLocation', 'net.minecraft.util.Mth', 'net.minecraft.world.entity.Entity'):
            L.append('import %s;' % imp)
        L.append('')
        L.append('public class %s<T extends Entity> extends EntityModel<T> {' % self.cls)
        L.append('    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation("%s", "%s"), "main");' % (modid, self.layer))
        L.append('    private final ModelPart root;')
        for p in fields:
            L.append('    private final ModelPart %s;' % p.name)
        L.append('')
        L.append('    public %s(ModelPart root) {' % self.cls)
        L.append('        this.root = root;')
        for p in fields:
            chain = []
            q = p
            while q is not None:
                chain.append(q.name)
                q = next((x for x in self.parts if x.name == q.parent), None) if q.parent else None
            expr = 'root'
            for n in reversed(chain):
                expr += '.getChild("%s")' % n
            L.append('        this.%s = %s;' % (p.name, expr))
        L.append('    }')
        L.append('')
        L.append('    public static LayerDefinition createBodyLayer() {')
        L.append('        MeshDefinition mesh = new MeshDefinition();')
        L.append('        PartDefinition root = mesh.getRoot();')
        for p in self.parts:
            parent = 'root' if not p.parent else 'p_' + p.parent
            cubes = 'CubeListBuilder.create()'
            for (u, v), c in zip(p.uv, p.cubes):
                x, y, z, w, h, d = c[:6]
                cubes += '.texOffs(%d, %d).addBox(%sf, %sf, %sf, %sf, %sf, %sf)' % (u, v, x, y, z, w, h, d)
            px, py, pz = p.pivot
            rx, ry, rz = p.rot
            if (rx, ry, rz) != (0, 0, 0):
                pose = 'PartPose.offsetAndRotation(%sf, %sf, %sf, %sf, %sf, %sf)' % (px, py, pz, rx, ry, rz)
            else:
                pose = 'PartPose.offset(%sf, %sf, %sf)' % (px, py, pz)
            L.append('        PartDefinition p_%s = %s.addOrReplaceChild("%s", %s, %s);' % (p.name, parent, p.name, cubes, pose))
        L.append('        return LayerDefinition.create(mesh, %d, %d);' % (self.tw, self.th))
        L.append('    }')
        L.append('')
        L.append('    @Override')
        L.append('    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {')
        for p in self.parts:
            a = p.anim
            base_x, base_y, base_z = p.rot
            if a == 'head':
                L.append('        %s.yRot = netHeadYaw * ((float) Math.PI / 180F);' % p.name)
                L.append('        %s.xRot = %sf + headPitch * ((float) Math.PI / 180F);' % (p.name, base_x))
            elif a in ('leg_a', 'leg_b', 'arm_a', 'arm_b'):
                phase = '' if a in ('leg_a', 'arm_b') else ' + (float) Math.PI'
                amp = '1.4F' if a.startswith('leg') else '1.0F'
                L.append('        %s.xRot = %sf + Mth.cos(limbSwing * 0.6662F%s) * %s * limbSwingAmount;' % (p.name, base_x, phase, amp))
            elif a == 'spin':
                L.append('        %s.yRot = ageInTicks * 0.6F;' % p.name)
            elif a == 'spin_fast':
                L.append('        %s.yRot = ageInTicks * 1.4F;' % p.name)
            elif a == 'bob':
                L.append('        %s.y = %sf + Mth.sin(ageInTicks * 0.15F) * 1.2F;' % (p.name, p.pivot[1]))
            elif a == 'wing_a':
                L.append('        %s.zRot = %sf + Mth.sin(ageInTicks * 1.2F) * 0.6F;' % (p.name, base_z))
            elif a == 'wing_b':
                L.append('        %s.zRot = %sf - Mth.sin(ageInTicks * 1.2F) * 0.6F;' % (p.name, base_z))
            elif a == 'sway':
                L.append('        %s.zRot = %sf + Mth.sin(ageInTicks * 0.1F) * 0.08F;' % (p.name, base_z))
            elif a == 'tail':
                L.append('        %s.yRot = Mth.cos(limbSwing * 0.6662F) * 0.4F * limbSwingAmount;' % p.name)
        L.append('    }')
        L.append('')
        L.append('    @Override')
        L.append('    public void renderToBuffer(PoseStack pose, VertexConsumer buffer, int light, int overlay, float r, float g, float b, float a) {')
        top = [p for p in self.parts if not p.parent]
        for p in top:
            L.append('        %s.render(pose, buffer, light, overlay, r, g, b, a);' % p.name)
        L.append('    }')
        L.append('}')
        L.append('')
        return '\n'.join(L)


