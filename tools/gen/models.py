def quadruped(cls, layer, body, legs, head, colors, extras=()):
    """body=(w,h,d), legs=(w,h), head=(w,h,d); colors=(body, legs, head)."""
    bw, bh, bd = body
    lw, lh = legs
    hw, hh, hd = head
    cb, cl, ch = colors
    m = BoxModel(cls, layer)
    ground = 24
    body_y = ground - lh - bh
    m.part('body', (0, body_y, 0), [(-bw / 2, 0, -bd / 2, bw, bh, bd, cb)])
    m.part('head', (0, body_y + 1, -bd / 2), [(-hw / 2, -hh + 2, -hd, hw, hh, hd, ch, 'eyes')], anim='head')
    lx, lz = bw / 2 - lw / 2, bd / 2 - lw / 2 - 1
    m.part('leg_fl', (-lx, ground - lh, -lz), [(-lw / 2, 0, -lw / 2, lw, lh, lw, cl)], anim='leg_a')
    m.part('leg_fr', (lx, ground - lh, -lz), [(-lw / 2, 0, -lw / 2, lw, lh, lw, cl)], anim='leg_b')
    m.part('leg_bl', (-lx, ground - lh, lz), [(-lw / 2, 0, -lw / 2, lw, lh, lw, cl)], anim='leg_b')
    m.part('leg_br', (lx, ground - lh, lz), [(-lw / 2, 0, -lw / 2, lw, lh, lw, cl)], anim='leg_a')
    for e in extras:
        m.part(*e)
    return m


def drone(cls, layer, body_color, rotor_color):
    m = BoxModel(cls, layer)
    m.part('body', (0, 14, 0), [(-5, -5, -5, 10, 8, 10, body_color), (-2, -2, -6, 4, 4, 1, '#7ee6ff', 'glow')], anim='bob')
    m.part('rotor', (0, -6, 0), [(-8, 0, -1, 16, 1, 2, rotor_color), (-1, 0, -8, 2, 1, 16, rotor_color)], parent='body', anim='spin_fast')
    m.part('gun', (0, 3, 0), [(-1, 0, -7, 2, 2, 5, '#3b3b3b')], parent='body')
    return m


def beetle(cls, layer, shell, legs):
    m = BoxModel(cls, layer)
    m.part('body', (0, 17, 0), [(-5, -3, -7, 10, 5, 14, shell), (-4, -4, -6, 8, 1, 12, shell)])
    m.part('head', (0, 17, -7), [(-3, -2, -4, 6, 4, 4, legs, 'eyes'), (-3, -1, -7, 1, 1, 3, legs), (2, -1, -7, 1, 1, 3, legs)], anim='head')
    for i, z in enumerate((-4, 0, 4)):
        m.part('leg_l%d' % i, (-5, 19, z), [(-6, 0, -1, 6, 1, 2, legs)], anim='leg_a' if i % 2 else 'leg_b', rot=(0, 0, 0.5))
        m.part('leg_r%d' % i, (5, 19, z), [(0, 0, -1, 6, 1, 2, legs)], anim='leg_b' if i % 2 else 'leg_a', rot=(0, 0, -0.5))
    return m


def rocket(cls, layer, hull, trim):
    m = BoxModel(cls, layer, 128, 128)
    m.part('hull', (0, 24, 0), [(-6, -40, -6, 12, 34, 12, hull), (-5, -46, -5, 10, 6, 10, hull), (-3, -50, -3, 6, 4, 6, trim),
                                (-1, -53, -1, 2, 3, 2, trim), (-7, -30, -2, 1, 6, 4, '#7ec8ff', 'glow'), (-5, -6, -5, 10, 6, 10, '#3b3b3b')])
    for i, (x, z) in enumerate(((-7, 0), (7, 0), (0, -7), (0, 7))):
        w, d = (2, 6) if x else (6, 2)
        m.part('fin%d' % i, (x, 24, z), [(-w / 2, -14, -d / 2, w, 14, d, trim)])
    return m
