#!/usr/bin/env python3
"""Generates every Lodestar mod from the specs in tools/mods/.

Usage: python3 tools/build.py            (writes mods/<id>/gen, mods/<id>/resources, generated/merged, mods.txt)
"""
import importlib
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gen import ls  # noqa: E402
from mods import ORDER  # noqa: E402


CATEGORY_TITLES = [('MATERIALS', 'Materials'), ('MACHINES', 'Machines & Power'), ('LOGISTICS', 'Logistics & Automation'),
                   ('TOOLS', 'Tools, Gear & Gadgets'), ('ADVENTURE', 'Adventure'), ('WORLD', 'Exploration & World'), ('SPACE', 'Space'),
                   ('DECOR', 'Decoration')]


def write_modlist(mods):
    """MODS.md: every mod with its description, grouped like the in-game Field Guide."""
    out = ['# Lodestar mod list', '', '%d mods, all written for this pack. Generated by tools/build.py.' % len(mods), '']
    for key, title in CATEGORY_TITLES:
        group = [m for m in mods if m.tab == key]
        if not group:
            continue
        out += ['## %s (%d)' % (title, len(group)), '', '| Mod | ID | What it adds |', '|---|---|---|']
        for m in group:
            out.append('| %s | `%s` | %s |' % (m.name, m.modid, m.desc.replace('|', '/').replace('\n', ' ')))
        out.append('')
    (Path(__file__).resolve().parents[1] / 'MODS.md').write_text('\n'.join(out) + '\n')


def main():
    t0 = time.time()
    for name in ORDER:
        mod = importlib.import_module('mods.' + name)
        mod.build()
    mods = ls.build_all()
    write_modlist(mods)
    files = sum(len(m.files) for m in mods)
    print('generated %d mods, %d resource files in %.1fs' % (len(mods), files, time.time() - t0))


if __name__ == '__main__':
    main()
